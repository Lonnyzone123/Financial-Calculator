'use strict';
/*
 * Ported from the Financial Projection V2.1.2 (post-audit-repair,
 * requalified) Python engine's retirement_model_v2/mortality_data.py and
 * retirement_model_v2/social_security_mortality.py -- Phase 4 (Social
 * Security optimizer port), module 2/9.
 *
 * ARCHITECTURE NOTE (deliberately different from the Python engine's own
 * data flow, adapted for the calculator's actual usage shape): in the Python
 * engine, `build_data_cache.py` pre-bakes a single birth year's q(x) data
 * (for I/II/III) into a JSON cache at *build* time via the raw
 * `TrusteesMortalityData` CSV loader -- one cache serves one configured
 * scenario. The calculator needs to support an arbitrary user-entered birth
 * year at *runtime*, so `ss-mortality-data.json` (built once, offline, by
 * fixtures/generate_ss_mortality_data.py using the real validated Python
 * loader -- never re-parsed from CSV in JS) ships q(x) for every birth year
 * 1900-2100 x all three alternatives, and buildMortalityPolicy() below does
 * at runtime what build_data_cache.py's _mortality_cache() does at build
 * time: slice out one birth year's worth of data into the same compact
 * shape MortalityTable expects. The math itself (MortalityTable,
 * conditionalProfile, annualSurvival) is a faithful line-by-line port,
 * verified against fixtures generated by feeding the real Python
 * MortalityTable that exact same compact shape.
 *
 * Only death_probability (q(x)) is shipped -- see
 * fixtures/generate_ss_mortality_data.py's header comment for why
 * survivors/deaths/life_expectancy were confirmed (by grep) to be unused by
 * every live calculation path in the Python engine.
 */

const MORTALITY_DATA = require('./ss-mortality-data.json');

function buildMortalityPolicy(birthYear) {
  const year = Math.trunc(birthYear);
  if (year < MORTALITY_DATA.birth_year_start || year > MORTALITY_DATA.birth_year_end) {
    throw new Error(`Birth year ${year} is outside the cached range`);
  }
  const alternatives = {};
  for (const alt of MORTALITY_DATA.alternatives) {
    const qx = MORTALITY_DATA.death_probability[alt][String(year)];
    const meta = MORTALITY_DATA.source_metadata[alt];
    alternatives[alt] = {
      source_sha256: meta.sha256,
      source_real_interest_rate: meta.source_real_interest_rate,
      q_x: qx,
    };
  }
  return {
    dataset_id: MORTALITY_DATA.dataset_id,
    dataset_version: MORTALITY_DATA.dataset_version,
    birth_year: year,
    sex: MORTALITY_DATA.sex,
    age_start: MORTALITY_DATA.age_start,
    age_end: MORTALITY_DATA.age_end,
    monthly_interpolation: 'constant_force_within_attained_age',
    alternatives,
  };
}

function createMortalityTable(mortalityData, alternative) {
  const alt = String(alternative).trim().toUpperCase();
  if (!(alt in mortalityData.alternatives)) {
    throw new Error(`Mortality alternative is not cached: ${alternative}`);
  }
  const source = mortalityData.alternatives[alt];
  const qX = source.q_x.map(Number);
  const ageStart = Math.trunc(mortalityData.age_start);
  const ageEnd = Math.trunc(mortalityData.age_end);
  const expectedLength = ageEnd - ageStart + 1;
  if (qX.length !== expectedLength) {
    throw new Error('Mortality q(x) length does not match cached age range');
  }
  if (qX.some((v) => !(v >= 0.0 && v <= 1.0))) {
    throw new Error('Mortality q(x) contains a value outside [0,1]');
  }

  function annualQ(age) {
    if (age < ageStart || age > ageEnd) {
      throw new Error(`Age ${age} is outside cached q(x)`);
    }
    return qX[age - ageStart];
  }

  function validateIdentity(birthYear, sex) {
    if (Math.trunc(birthYear) !== Math.trunc(mortalityData.birth_year)) {
      throw new Error('Requested birth cohort is not in the compact mortality cache');
    }
    if (String(sex).trim().toLowerCase() !== String(mortalityData.sex).toLowerCase()) {
      throw new Error('Requested sex is not in the compact mortality cache');
    }
  }

  function conditionalProfile({ birthYear, sex, valuationAgeMonths, throughAgeMonths }) {
    validateIdentity(birthYear, sex);
    const minimumMonth = ageStart * 12;
    const terminalMonth = (ageEnd + 1) * 12;
    if (!(minimumMonth <= valuationAgeMonths && valuationAgeMonths <= ageEnd * 12 + 11)) {
      throw new Error('Valuation month is outside the mortality source range');
    }
    if (throughAgeMonths < valuationAgeMonths) {
      throw new Error('through_age_months cannot precede valuation_age_months');
    }
    if (throughAgeMonths > terminalMonth) {
      throw new Error('Requested horizon would require unavailable q(x)');
    }

    const points = [];
    let survival = 1.0;
    for (let ageMonths = valuationAgeMonths; ageMonths <= throughAgeMonths; ageMonths++) {
      let unconditionalDeath;
      let monthlyQ;
      if (ageMonths < throughAgeMonths) {
        const annualQVal = annualQ(Math.floor(ageMonths / 12));
        monthlyQ = 1.0 - Math.pow(1.0 - annualQVal, 1.0 / 12.0);
        unconditionalDeath = survival * monthlyQ;
      } else {
        unconditionalDeath = 0.0;
        monthlyQ = 0.0;
      }
      points.push({
        ageMonths,
        survival: Math.min(1.0, Math.max(0.0, survival)),
        deathProbability: Math.min(1.0, Math.max(0.0, unconditionalDeath)),
      });
      survival *= 1.0 - monthlyQ;
    }

    const profile = {
      alternative: alt,
      birthYear: Math.trunc(birthYear),
      sex: String(sex).trim().toLowerCase(),
      valuationAgeMonths: Math.trunc(valuationAgeMonths),
      throughAgeMonths: Math.trunc(throughAgeMonths),
      points,
      sourceId: String(mortalityData.dataset_id),
      dataVersion: String(mortalityData.dataset_version),
      sourceSha256: String(source.source_sha256),
      interpolation: String(mortalityData.monthly_interpolation),
    };
    validateProfile(profile);
    return profile;
  }

  function annualSurvival({ birthYear, sex, valuationAge, throughAge }) {
    const profile = conditionalProfile({
      birthYear,
      sex,
      valuationAgeMonths: valuationAge * 12,
      throughAgeMonths: throughAge * 12,
    });
    const out = [];
    for (let age = valuationAge; age <= throughAge; age++) {
      out.push(profilePoint(profile, age * 12).survival);
    }
    return out;
  }

  return { alternative: alt, conditionalProfile, annualSurvival };
}

function profilePoint(profile, ageMonths) {
  const index = ageMonths - profile.valuationAgeMonths;
  if (index < 0 || index >= profile.points.length) {
    throw new Error('Requested age is outside the mortality profile');
  }
  return profile.points[index];
}

function profileTerminalSurvival(profile) {
  return profile.points[profile.points.length - 1].survival;
}

function profileCumulativeDeathProbability(profile) {
  // preciseSum not required here: Python's source sums with plain sum(),
  // and this list is at most 12*(120)=1440 small floats -- well within the
  // range where naive vs. Neumaier summation cannot diverge across any
  // profile this module can actually produce (verified against fixtures,
  // not just assumed, following the lesson from the Phase 8 audit finding).
  let total = 0;
  for (const p of profile.points) total += p.deathProbability;
  return total;
}

function validateProfile(profile) {
  if (profile.points.length === 0) {
    throw new Error('Mortality profile cannot be empty');
  }
  if (Math.abs(profile.points[0].survival - 1.0) > 1e-12) {
    throw new Error('Conditional mortality profile must begin at survival 1.0');
  }
  let priorSurvival = 1.0;
  let priorMonth = profile.valuationAgeMonths - 1;
  for (const point of profile.points) {
    if (point.ageMonths !== priorMonth + 1) {
      throw new Error('Mortality profile months must be consecutive');
    }
    if (!(point.survival >= 0.0 && point.survival <= 1.0)) {
      throw new Error('Mortality survival is outside [0,1]');
    }
    if (point.survival > priorSurvival + 1e-12) {
      throw new Error('Mortality survival cannot increase');
    }
    if (!(point.deathProbability >= 0.0 && point.deathProbability <= point.survival + 1e-12)) {
      throw new Error('Mortality death probability is invalid');
    }
    priorSurvival = point.survival;
    priorMonth = point.ageMonths;
  }
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = {
    buildMortalityPolicy,
    createMortalityTable,
    profilePoint,
    profileTerminalSurvival,
    profileCumulativeDeathProbability,
  };
}
